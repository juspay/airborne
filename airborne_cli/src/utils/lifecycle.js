// Release lifecycle helpers for airborne-devkit. The server actions are passed in so the
// behaviour can be exercised without a server; index.js supplies the real ones.

// A release has one control and one experimental variant, and the experiment service
// refuses a ramp above 50. Airborne reports that refusal as an "unresolved" write and
// pauses the application, so reject it here before anything is sent.
export const MAX_RAMP_PERCENTAGE = 50;

export function parseRampPercentage(value) {
  const text = String(value).trim();
  if (!/^\d+$/.test(text) || Number(text) > MAX_RAMP_PERCENTAGE) {
    throw new Error(
      `Traffic percentage must be a whole number from 0 to ${MAX_RAMP_PERCENTAGE}, got "${value}"`
    );
  }
  return Number(text);
}

// "control" and "release" name the two outcomes; anything else is taken as a literal id.
// The ids are generated by the experiment service, so they are read from the release.
export async function resolveVariant(choice, release, actions, base) {
  if (choice !== "control" && choice !== "release") return choice;
  // GetRelease names its path parameter releaseId, unlike the lifecycle operations.
  const { experiment } = await actions.GetReleaseAction(null, {
    ...base,
    releaseId: release,
  });
  const variants = experiment?.experiment_variants;
  if (!variants) {
    throw new Error(`Release ${release} has no experiment to conclude`);
  }
  if (choice === "control") return variants.control;
  if (variants.experimentals?.length !== 1) {
    throw new Error(
      `Release ${release} has ${variants.experimentals?.length ?? 0} experimental variants; pass one by id with --variant`
    );
  }
  return variants.experimentals[0];
}

export async function runLifecycle(kind, args, actions) {
  const base = {
    organisation: args.organisation,
    application: args.application,
    token: args.token,
  };
  const reason = args.reason ? { change_reason: args.reason } : {};
  switch (kind) {
    case "ramp":
      return actions.RampReleaseAction(null, {
        ...base,
        release_id: args.releaseId,
        traffic_percentage: parseRampPercentage(args.percentage),
        ...reason,
      });
    case "conclude": {
      const chosen_variant = await resolveVariant(
        args.variant,
        args.releaseId,
        actions,
        base
      );
      return actions.ConcludeReleaseAction(null, {
        ...base,
        release_id: args.releaseId,
        chosen_variant,
        ...reason,
      });
    }
    case "discard":
      return actions.DiscardReleaseAction(null, {
        ...base,
        release_id: args.releaseId,
        ...reason,
      });
    case "rollback":
      return actions.RollbackReleaseAction(null, {
        ...base,
        release_id: args.releaseId,
        reason: args.reason,
        emergency: Boolean(args.emergency),
        confirm_sensitive_risk: Boolean(args.confirmSensitiveRisk),
      });
    default:
      throw new Error(`Unknown lifecycle action: ${kind}`);
  }
}

// One readable line: HTTP status, the server's error code when it sent one, and its message.
// An unresolved write also names its operation so it can be passed to ResolveControlCenterOperation.
export function describeFailure(err) {
  const status = err?.$metadata?.httpStatusCode ?? err?.$response?.statusCode;
  const parts = [];
  if (status) parts.push(`HTTP ${status}`);
  if (err?.code) parts.push(String(err.code));
  parts.push(err?.message || String(err));
  const line = parts.join(": ");
  return err?.operation_id ? `${line} (operation ${err.operation_id})` : line;
}
